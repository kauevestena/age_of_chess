"""Export the validated Python rulesets for the browser; --check is the CI drift gate."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from implementation.age_of_chess.rules_loader import load_ruleset

SOURCES = ['rulesets/default.yaml', 'rulesets/open_field.yaml']
rulesets = {}
for source in SOURCES:
    game = load_ruleset(str(ROOT / source)).game.model_dump(by_alias=True)
    rulesets[game['mode']] = game
text = '// Generated by web/scripts/export_rules.py. Edit ' + ' and '.join(SOURCES) + '.\n'
text += 'export const RULESETS = ' + json.dumps(rulesets, indent=2, ensure_ascii=False) + ';\n'
text += '''
// The active ruleset. Engine entry points switch it to match the state they are given,
// so the AI worker, saves and replays follow each game's own mode.
export const RULES = {};
export function useRuleset(mode) {
  if (!RULESETS[mode]) throw Error(`Unknown ruleset: ${mode}`);
  for (const key of Object.keys(RULES)) delete RULES[key];
  Object.assign(RULES, structuredClone(RULESETS[mode]));
  return RULES;
}
useRuleset("warfare");
'''
target = ROOT / 'web/src/rules.mjs'
if '--check' in sys.argv:
    if target.read_text() != text:
        raise SystemExit('Browser rules are stale. Run .venv/bin/python web/scripts/export_rules.py')
else:
    target.write_text(text)
